#!/usr/bin/python3
"""assemble_packet.py — assemble <packet dir>/: 00 motion PDF (from the finisher's .docx via LibreOffice, same path
bundle 12 used), 01..NN exhibits as PDFs (originals kept beside), 99_PACKET_INDEX.md with page counts.
Promoted from $M/_assemble_packet.py (2026-10-25); the exhibit list comes from the stub's NEW EVIDENCE BLOCK rows
(letter / title / [doc:<file>]): PDF = <doc stem>.pdf in --exhibits-dir, original = the [doc:] file when it is not a PDF.

Run: cd <home> && env PYTHONPATH=$PWD /usr/bin/python3 -m pipeline.packet.assemble_packet --m <motion dir>
     [--stub ...] [--draft-docx <M>/motion_to_vacate_M1_DRAFT.docx] [--packet-dir <M>/PACKET] [--exhibits-dir <M>]
"""
from pathlib import Path
from core.entropy_paths import entropy_root as _eroot, package_root as _epkg, hermes_home as _ehermes
import argparse
import datetime as dt
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if not (ROOT / "pipeline" / "m1.py").exists():
    ROOT = _eroot()
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from pypdf import PdfReader  # noqa: E402
from pipeline.packet.manifest import read_manifest, default_stub  # noqa: E402

# No case lives in code (S-packet-defaults, 2026-10-27): the motion dir is required and every label comes from the chain
# (PACKET_* env / CLI) or is derived from the case registry at runtime. A default that names a party, counsel, control
# number or judge is a hardcode of ONE case — the next case silently inherits it.
DEFAULT_M = None
DEFAULT_MOTION_NAME = "00_Motion"
DEFAULT_MOTION_DESC = "Motion — incl. RELIEF SOUGHT, VERIFICATION, CERTIFICATE OF SERVICE, [PROPOSED] ORDER"
DEFAULT_INDEX_TITLE = "# PACKET INDEX"
DEFAULT_CAPTION = None      # derived: registry caption + docket no. (pipeline.m1_finisher.registry_caption_ctx)
DEFAULT_TODO = ("Still TODO before filing (not generated by the pipeline): the forum's motion cover sheet, if any; "
                "service on counsel of record per the forum's service rule.")


def derive_caption(m_dir) -> str:
    """Caption line for the packet index from the case registry (never a literal). Empty string when unresolved."""
    try:
        from pipeline.m1_finisher import registry_caption_ctx
        parts = Path(str(m_dir)).parts
        slug = next((parts[i + 1] for i, x in enumerate(parts) if x == "cases" and i + 1 < len(parts)), None)
        reg = registry_caption_ctx(slug) if slug else None
        if not reg: return ""
        cap = reg.get("caption") or {}
        d = (cap.get("defendants") or [{}])[0].get("name", "")
        return f"{cap.get('plaintiff', '')} v. {d}, No. {reg.get('docket_no', '')}".strip()
    except Exception:
        return ""


def npages(p):
    return len(PdfReader(str(p)).pages)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="numbered PACKET/ + 99_PACKET_INDEX.md from the stub's exhibit rows")
    ap.add_argument("--m", required=True, help="motion dir")
    ap.add_argument("--stub", default=None, help="stub/manifest with the NEW EVIDENCE BLOCK (default <M>/EXHIBITS.md else <M>/motion_to_vacate.md)")
    ap.add_argument("--draft-docx", default=None, help="the finisher's .docx (default <M>/motion_to_vacate_M1_DRAFT.docx)")
    ap.add_argument("--packet-dir", default=None, help="output dir (default <M>/PACKET)")
    ap.add_argument("--exhibits-dir", default=None, help="where the exhibit PDFs/originals are (default <M>)")
    ap.add_argument("--motion-name", default=DEFAULT_MOTION_NAME)
    ap.add_argument("--motion-desc", default=DEFAULT_MOTION_DESC)
    ap.add_argument("--index-title", default=DEFAULT_INDEX_TITLE)
    ap.add_argument("--caption", default=None, help="index caption line; default derived from the case registry")
    ap.add_argument("--todo", default=DEFAULT_TODO)
    a = ap.parse_args(argv)

    M = Path(a.m)
    if not a.caption: a.caption = derive_caption(M)
    P = Path(a.packet_dir) if a.packet_dir else M / "PACKET"
    P.mkdir(parents=True, exist_ok=True)
    EX = Path(a.exhibits_dir) if a.exhibits_dir else M
    stub = Path(a.stub) if a.stub else default_stub(M)

    DRAFT_DOCX = Path(a.draft_docx) if a.draft_docx else M / "motion_to_vacate_M1_DRAFT.docx"
    assert DRAFT_DOCX.exists(), DRAFT_DOCX
    from generation.finalize_brief import convert_to_pdf
    motion_pdf = convert_to_pdf(DRAFT_DOCX)
    assert motion_pdf and Path(motion_pdf).exists(), "docx->pdf failed for the motion"

    rows = []
    dst0 = P / f"{a.motion_name}.pdf"
    shutil.copy2(motion_pdf, dst0)
    shutil.copy2(DRAFT_DOCX, P / f"{a.motion_name}.docx")
    rows.append(("—", dst0.name, npages(dst0), a.motion_desc))

    exhibits = read_manifest(stub, bases=[EX, M])
    for i, r in enumerate(exhibits, 1):
        letter, doc = r["letter"], Path(r["doc"]).name
        src = EX / (Path(doc).stem + ".pdf")
        if not src.exists():
            src = M / (Path(doc).stem + ".pdf")
        assert src.exists(), src
        dst = P / f"{i:02d}_EXHIBIT_{letter}_{src.stem.replace('motion_EXHIBIT_' + letter + '_', '')}.pdf"
        shutil.copy2(src, dst)
        if not doc.lower().endswith(".pdf"):
            o = EX / doc
            if not o.exists():
                o = M / doc
            if o.exists():
                shutil.copy2(o, P / f"{i:02d}_EXHIBIT_{letter}_original{o.suffix}")
        rows.append((letter, dst.name, npages(dst), r["title"]))

    total = sum(r[2] for r in rows)
    try:
        rel = M.resolve().relative_to(ROOT.resolve())
    except ValueError:
        rel = M
    lines = [a.index_title, a.caption,
             f"Assembled {dt.datetime.now().strftime('%Y-%m-%d %H:%M')} from {rel} · NOT e-filed · cart/submit is the user's.",
             "", "| # | Exhibit | File | Pages | Description |", "|---|---|---|---|---|"]
    for n, r in enumerate(rows):
        lines.append(f"| {n:02d} | {r[0]} | {r[1]} | {r[2]} | {r[3]} |")
    lines += ["", f"**Total pages: {total}**", "",
              "Originals kept beside the PDFs as `NN_EXHIBIT_X_original.<ext>` (email text, CSV, DOCX). Source files remain in the motion dir as `motion_EXHIBIT_<letter>_*.`",
              a.todo]
    (P / "99_PACKET_INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
